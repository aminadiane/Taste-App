/* pallas taste engine — Taste Profile snapshots. Builds a profile from an analysis result and compares snapshots.
   A profile is a derived, regenerable view: the event log and the content metadata remain the source of truth.
   All wording is templated from the statistics; nothing is generated by a language model. The `interpretations`
   slot is reserved for later AI-written commentary, which must cite findings and never replace them. */
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else { root.Pallas = root.Pallas || {}; root.Pallas.taste = root.Pallas.taste || {}; root.Pallas.taste.profiles = api; }
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  const SCHEMA = 'pallas.taste-profile/1';
  const RANK = { 'well supported': 3, emerging: 2, tentative: 1 };
  const ESTABLISHED_AFTER = 30;   // judgments needed before a profile with a well-supported finding is called established

  // Deterministic digest of the judgments a profile was based on (FNV-1a, 32-bit), so snapshots can be matched to input.
  function digest(judgments) {
    const s = Object.keys(judgments).sort().map((k) => k + '=' + judgments[k]).join(';');
    let h = 0x811c9dc5;
    for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
    return h.toString(16).padStart(8, '0');
  }

  const list = (xs) => (xs.length <= 1 ? xs.join('') : xs.slice(0, -1).join(', ') + ' and ' + xs[xs.length - 1]);
  const trimFinding = (f) => ({
    feature: f.feature, dimension: f.dimension, value: f.value, label: f.label, basis: f.basis, subjective: f.basis === 'interpretation',
    aliases: (f.aliases || []).map((a) => a.feature), strength: f.strength, explainedBy: f.explainedBy ? f.explainedBy.feature : null, inseparableFrom: f.inseparableFrom ? f.inseparableFrom.feature : null, stats: f.stats, explanation: f.explanation, notes: f.notes || [],
    evidence: { supporting: f.evidence.supporting.map((e) => e.item), contradicting: f.evidence.contradicting.map((e) => e.item), supportingWorks: f.evidence.supportingWorks },
  });

  function evidenceLevel(result) {
    if (result.status !== 'ok') return result.status;
    const s = result.findings.filter((f) => !f.explainedBy && !f.inseparableFrom).map((f) => RANK[f.strength]);
    if (s.includes(3) && result.counts.judged >= ESTABLISHED_AFTER) return 'established';
    if (s.some((x) => x >= 2)) return 'developing';
    if (s.length) return 'early';
    return 'no-pattern';
  }

  // Up to three leanings and two aversions for the signature, one per dimension, observed or measured before interpreted.
  function pickSignature(findings) {
    // Several liked values may share a dimension (lyrical and experimental prose); a disliked value is left out
    // when its dimension already appears among the likes, since it is usually the mirror image (low-key liked, mid-key disliked).
    const sorted = (dir) => findings.filter((f) => f.direction === dir && !f.explainedBy && !f.inseparableFrom)
      .sort((a, b) => RANK[b.strength] - RANK[a.strength] || (a.basis === 'interpretation') - (b.basis === 'interpretation') || a.stats.p - b.stats.p);
    const liked = sorted('liked').slice(0, 3), seen = new Set();
    const mirror = (f) => liked.some((l) => l.dimension === f.dimension && RANK[l.strength] >= RANK[f.strength]);
    const disliked = sorted('disliked').filter((f) => !mirror(f) && !seen.has(f.dimension) && seen.add(f.dimension)).slice(0, 2);
    return { liked, disliked };
  }

  function signature(result, level, noun) {
    const n = result.counts.judged;
    if (level === 'insufficient') return { summary: `Not enough judgments yet to describe a taste: ${n} so far, ${result.options.minJudgments} needed before any pattern is reported.`, terms: [], statements: [] };
    if (level === 'one-sided') return { summary: `Every ${noun} judged so far was ${result.counts.likes ? 'liked' : 'disliked'}, so there is nothing yet to compare.`, terms: [], statements: [] };
    if (level === 'no-pattern') {
      const spread = result.spread.reading === 'broad' ? ` Likes are spread as widely as everything judged.` : '';
      return { summary: `No characteristic stands out yet across ${n} judged ${noun}s.${spread}`, terms: [], statements: [] };
    }
    // Only emerging and well-supported findings reach the signature (stress tests: tentative findings are common by chance).
    // Well supported → "A clear leaning towards"; emerging → "Early signs of a leaning towards".
    const { liked, disliked } = pickSignature(result.findings.filter((f) => f.strength !== 'tentative'));
    const parts = [];
    const clear = liked.filter((f) => f.strength === 'well supported'), early = liked.filter((f) => f.strength === 'emerging');
    if (clear.length) parts.push('A clear leaning towards ' + list(clear.map((f) => f.label)) + '.');
    if (early.length) parts.push((clear.length ? 'Early signs of a leaning towards ' : 'Early signs of a leaning towards ') + list(early.map((f) => f.label)) + '.');
    if (disliked.length) parts.push((disliked.every((f) => f.strength === 'emerging') ? 'Possibly less drawn to ' : 'Less drawn to ') + list(disliked.map((f) => f.label)) + '.');
    if (!parts.length) return { summary: `Some characteristics may matter, but nothing is clear yet across ${n} judged ${noun}s.`, terms: [], statements: [] };
    const combos = (result.combinations || []).filter((c) => c.strength !== 'tentative').slice(0, 1);
    if (combos.length) parts.push(`Notably, ${combos[0].features[0].label} with ${combos[0].features[1].label} (${combos[0].stats.likedWhenPresent} of ${combos[0].stats.exposed} liked).`);
    const statements = [...liked, ...disliked].map((f) => ({ text: f.explanation, feature: f.feature, strength: f.strength, subjective: f.basis === 'interpretation' }));
    return { summary: parts.join(' '), terms: [...liked, ...disliked].map((f) => f.feature), statements };
  }

  /* build(result, { judgments, history, generatedAt })  → profile snapshot (plain JSON).
     generatedAt is passed in so the same input always gives the same output. */
  function build(result, { judgments = {}, history = [], generatedAt = null } = {}) {
    const noun = result.area === 'cinema' ? 'still' : 'passage';
    const level = evidenceLevel(result);
    const sig = signature(result, level, noun);
    const used = new Set();
    for (const f of result.findings) { used.add(f.feature); (f.aliases || []).forEach((a) => used.add(a.feature)); }
    for (const c of result.combinations) c.features.forEach((f) => used.add(f.feature));
    const glossary = [...used].sort().map((k) => {
      const f = result.findings.find((x) => x.feature === k) || result.combinations.flatMap((c) => c.features).find((x) => x.feature === k) || result.findings.flatMap((x) => x.aliases).find((x) => x.feature === k) || { feature: k };
      return { term: k, label: f.label, definition: f.definition, dimension: f.dimensionLabel, basis: f.basis };
    });
    const limitations = [
      'Associations describe this person\'s judgments of this library only; they are not a comparison with other people.',
      'Characteristics that always appear together in the works judged cannot be separated and are reported together.',
      'Strength labels come from exact tests corrected for the number of characteristics tested; tentative findings may disappear with more judgments.',
    ];
    if (result.findings.some((f) => f.basis === 'interpretation')) limitations.push('Findings marked subjective rest on atmosphere or tone readings, which are interpretations rather than observations.');
    if (result.counts.notInLibrary) limitations.push(`${result.counts.notInLibrary} judged item(s) are not in the current library and were left out.`);
    const lastEvent = history.length ? history[history.length - 1].t : null;
    return {
      schema: SCHEMA, kind: 'taste-profile', area: result.area, generatedAt,
      engine: result.engine, options: result.options,
      basedOn: { ...result.counts, eventCount: history.length, lastEventAt: lastEvent, judgmentsDigest: digest(judgments) },
      evidenceLevel: level,
      signature: sig,
      preferred: result.findings.filter((f) => f.direction === 'liked').map(trimFinding),
      disliked: result.findings.filter((f) => f.direction === 'disliked').map(trimFinding),
      combinations: result.combinations.map((c) => ({ features: c.features.map((f) => f.feature), labels: c.features.map((f) => f.label), direction: c.direction, strength: c.strength, stats: c.stats, explanation: c.explanation, evidence: { supporting: c.evidence.supporting.map((e) => e.item), contradicting: c.evidence.contradicting.map((e) => e.item) } })),
      notYetClear: result.insufficient.filter((x) => x.exposed > 0).slice(0, 12).map((x) => ({ feature: x.feature, label: x.label, exposed: x.exposed, liked: x.liked })),
      spread: result.spread, consistency: result.consistency,
      terminology: glossary,
      interpretations: [],
      limitations,
    };
  }

  // What changed between two snapshots of the same area: for the Journal's history of taste.
  function compare(older, newer) {
    const key = (f, dir) => `${dir}:${f.feature}`;
    const map = (p) => new Map([...p.preferred.map((f) => [key(f, 'liked'), f]), ...p.disliked.map((f) => [key(f, 'disliked'), f])]);
    const a = map(older), b = map(newer), out = { added: [], removed: [], strengthened: [], weakened: [], unchanged: [] };
    for (const [k, f] of b) {
      if (!a.has(k)) out.added.push({ key: k, label: f.label, strength: f.strength });
      else { const d = RANK[f.strength] - RANK[a.get(k).strength]; (d > 0 ? out.strengthened : d < 0 ? out.weakened : out.unchanged).push({ key: k, label: f.label, from: a.get(k).strength, to: f.strength }); }
    }
    for (const [k, f] of a) if (!b.has(k)) out.removed.push({ key: k, label: f.label, strength: f.strength });
    return { from: older.generatedAt, to: newer.generatedAt, evidenceLevel: [older.evidenceLevel, newer.evidenceLevel], ...out };
  }

  /* A draft natural-language reading of a profile, for review before any screen is designed. Deterministic: every
     sentence is a template filled from a finding's counts, definition and evidence. It never adds a claim the statistics
     do not make, never ranks tastes, and never suggests a dislike is mistaken. titleOf(itemId) → display name. */
  function narrative(profile, { titleOf = (id) => id, workOf = () => null } = {}) {
    const noun = profile.area === 'cinema' ? 'still' : 'passage', unit = profile.area === 'cinema' ? 'film' : 'book';
    const b = profile.basedOn, out = [];
    const pc = (x) => Math.round(x * 100) + '%';
    const lower = (s) => (s ? s.charAt(0).toLowerCase() + s.slice(1).replace(/\.$/, '') : '');
    // Examples from different works where possible, so one film does not stand for the whole pattern.
    const examples = (ids, k = 3) => {
      const seen = new Set(), pick = [];
      for (const id of ids) { const w = workOf(id) || id; if (!seen.has(w)) { seen.add(w); pick.push(id); } if (pick.length === k) break; }
      return pick.map(titleOf).join('; ');
    };
    const def = (f) => (profile.terminology.find((t) => t.term === f.feature) || {}).definition;
    if (profile.evidenceLevel === 'insufficient' || profile.evidenceLevel === 'one-sided') return [profile.signature.summary];
    out.push(`Across ${b.judged} ${noun}s from ${b.works} ${unit}s you liked ${b.likes} (${pc(b.likeRate)}). What follows compares the ${noun}s you liked with the ones you did not; it describes your choices in this collection, not a fixed type.`);
    const main = (list) => list.filter((f) => !f.explainedBy && !f.inseparableFrom && f.strength !== 'tentative');
    const liked = main(profile.preferred);
    // As in the signature: a disliked value whose dimension already has an equally strong liked value is its mirror image.
    const disliked = main(profile.disliked).filter((f) => !liked.some((l) => l.dimension === f.dimension && RANK[l.strength] >= RANK[f.strength]));
    if (!liked.length && !disliked.length) {
      out.push(`No characteristic separates your likes from your dislikes clearly yet${profile.spread.reading === 'broad' ? '; your likes range as widely as everything you judged' : ''}.`);
    }
    for (const f of liked) {
      const s = f.stats, d = def(f);
      out.push(`${f.strength === 'well supported' ? 'Clearly' : 'Possibly'}, ${f.label}${d ? ` (${lower(d)})` : ''}: you liked ${s.likedWhenPresent} of ${s.exposed} (${pc(s.rateWhenPresent)}), against ${pc(s.rateWhenAbsent)} of the rest, across ${f.evidence.supportingWorks} ${unit}s. For example: ${examples(f.evidence.supporting)}.${f.subjective ? ' This rests on a subjective reading of mood or tone.' : ''}`);
    }
    for (const c of profile.combinations.filter((x) => x.strength !== 'tentative').slice(0, 2)) {
      out.push(`Together, ${c.labels[0]} with ${c.labels[1]} stands out: ${c.stats.likedWhenPresent} of ${c.stats.exposed} liked, more than either alone (${pc(c.stats.rateFirstAlone)} and ${pc(c.stats.rateSecondAlone)}). For example: ${examples(c.evidence.supporting, 2)}.`);
    }
    if (disliked.length) out.push(`You were less drawn to ${list(disliked.map((f) => `${f.label} (${f.stats.likedWhenPresent} of ${f.stats.exposed} liked)`))}. That is a description of your judgments, not a gap to correct.`);
    const lbl = (k) => (profile.terminology.find((t) => t.term === k) || {}).label || k;
    const related = [...profile.preferred, ...profile.disliked].filter((f) => f.explainedBy && f.strength !== 'tentative').slice(0, 3);
    if (related.length) out.push(`Some characteristics only appear to matter because they travel with the ones above: ${list(related.map((f) => `${f.label} (accounted for by ${lbl(f.explainedBy)})`))}.`);
    const together = [...profile.preferred, ...profile.disliked].filter((f) => f.inseparableFrom && f.strength !== 'tentative').slice(0, 3);
    if (together.length) out.push(`These cannot yet be told apart from the characteristics above, because they occur in nearly the same works: ${list(together.map((f) => `${f.label} with ${lbl(f.inseparableFrom)}`))}.`);
    const open = (profile.notYetClear || []).filter((x) => x.exposed >= 2).slice(0, 3);
    if (open.length) out.push(`Too few examples to say anything yet about ${list(open.map((x) => `${x.label} (${x.exposed} judged)`))}.`);
    return out;
  }

  return { SCHEMA, build, compare, digest, narrative };
});
