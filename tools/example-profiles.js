// Writes example Taste Profiles for the simulated users to docs/examples/taste-profiles/ for review.
// Usage: node tools/example-profiles.js
// Deterministic: the same engine and data always produce the same files.
const fs = require('node:fs');
const path = require('node:path');
const ROOT = path.join(__dirname, '..');
const A = require(path.join(ROOT, 'js', 'taste', 'analyse.js'));
const P = require(path.join(ROOT, 'js', 'taste', 'profile.js'));
const U = require(path.join(ROOT, 'tests', 'fixtures', 'simulated-users.js'));
const OUT = path.join(ROOT, 'docs', 'examples', 'taste-profiles');
fs.mkdirSync(OUT, { recursive: true });

const AT = '2026-10-21T00:00:00.000Z';
const rows = [];
for (const name of Object.keys(U.USERS)) {
  const r = U.run(name);
  const result = A.analyse({ judgments: r.judgments, library: r.library, history: r.history });
  const profile = P.build(result, { judgments: r.judgments, history: r.history, generatedAt: AT });
  fs.writeFileSync(path.join(OUT, `${name}.json`), JSON.stringify({ simulatedUser: { name, area: r.user.area, description: r.user.describe, seed: r.user.seed, library: r.user.area === 'literature' ? 'synthetic test corpus (36 passages)' : 'real cinema library (89 stills)' }, profile }, null, 2) + '\n');
  rows.push({ name, r, result, profile });
}

const fmt = (f) => `${f.label} (${f.strength}${f.explainedBy ? `, accounted for by ${f.explainedBy}` : ''}; ${f.stats.likedWhenPresent}/${f.stats.exposed} liked, q ${f.stats.q})`;
let md = `# Example Taste Profiles\n\nGenerated by \`node tools/example-profiles.js\` with engine ${A.VERSION} on ${AT.slice(0, 10)}. Each simulated user follows a written rule with seeded randomness (\`tests/fixtures/simulated-users.js\`). The JSON files hold the complete profiles, with evidence lists, statistics, glossary and limitations. This page lists the parts to review.\n\nThe literature users run on a synthetic test corpus because the real library has only five passages.\n`;
for (const { name, r, result, profile } of rows) {
  md += `\n## ${name}\n\n*${r.user.describe}*\n\n`;
  md += `- **Judged:** ${result.counts.judged} (${result.counts.likes} liked). **Evidence level:** ${profile.evidenceLevel}. **Spread:** ${result.spread.reading ?? 'n/a'}${result.spread.overall != null ? ` (${result.spread.overall})` : ''}.\n`;
  md += `- **Signature:** ${profile.signature.summary}\n`;
  const top = (list) => list.slice(0, 5).map((f) => `  - ${fmt(f)}`).join('\n') || '  - none';
  md += `- **Liked characteristics:**\n${top(profile.preferred)}\n- **Disliked characteristics:**\n${top(profile.disliked)}\n`;
  md += `- **Combinations:** ${profile.combinations.slice(0, 3).map((c) => `${c.labels.join(' + ')} (${c.strength}; ${c.stats.likedWhenPresent}/${c.stats.exposed} liked)`).join('; ') || 'none'}\n`;
  if (result.consistency.changedJudgments.length) md += `- **Reversed judgments:** ${result.consistency.changedJudgments.join(', ')}\n`;
}
fs.writeFileSync(path.join(OUT, 'README.md'), md);
console.log(`wrote ${rows.length} profiles to docs/examples/taste-profiles/`);
